import { File } from 'expo-file-system';
import { Platform } from 'react-native';

import { getAuthToken, isSessionExpired, notifyUnauthorized } from './authBridge';
import { getApiBaseUrl } from './config';
import { ApiError } from './errors';
import { splitFrames } from './stream';
import type { Document, UploadFrame, UploadOutcome, UploadProgress } from './types';

/**
 * `POST /api/documents` — multipart upload that answers with an SSE progress
 * stream (DOCUMENTS.md §4).
 *
 * This does not go through `client.ts`: `apiRequestRaw` sets
 * `Content-Type: application/json` and stringifies the body, which would destroy
 * a `FormData` payload (the boundary must be generated by the platform). Every
 * other rule is kept — bearer token, expiry pre-emption, `401 → /login`, and the
 * `X-Request-ID` on the error.
 *
 * The outcome is decided by the response content type, exactly as §4.3 states:
 * a `201` is a stream, a `200` is the duplicate JSON body, and `400`/`413` are
 * ordinary errors.
 */

/** A picked file, as far as this module needs to know. */
export type UploadAsset = {
  uri: string;
  name: string;
  mimeType?: string | null;
  size?: number | null;
  /** Web only: the real `File` from the picker. */
  file?: unknown;
};

export type UploadHandlers = {
  onProgress?: (progress: UploadProgress) => void;
  signal?: AbortSignal;
};

const DATA_PREFIX = 'data:';

/** Parses one upload SSE block. Returns null for noise and `[DONE]`. */
export function parseUploadFrame(block: string): UploadFrame | null {
  const trimmed = block.trim();
  if (!trimmed) return null;

  const data = trimmed
    .split('\n')
    .filter((line) => line.startsWith(DATA_PREFIX))
    .map((line) => line.slice(DATA_PREFIX.length).trim())
    .join('\n');

  if (!data || data === '[DONE]') return null;

  try {
    const parsed = JSON.parse(data) as UploadFrame;
    if (parsed && typeof parsed === 'object') return parsed;
    return null;
  } catch {
    return null;
  }
}

function multipartBody(asset: UploadAsset): FormData {
  const form = new FormData();

  // On web the picker already handed us a File; on native the platform needs an
  // expo-file-system `File`, which expo/fetch serialises as a multipart part.
  const part = Platform.OS === 'web' && asset.file ? asset.file : new File(asset.uri);
  form.append('file', part as unknown as Blob, asset.name);

  return form;
}

async function errorFrom(response: Response): Promise<ApiError> {
  const requestId = response.headers.get('X-Request-ID') ?? undefined;
  let code = 'error';
  let message = `Upload failed (${response.status})`;
  try {
    const payload = (await response.json()) as { error?: { code?: string; message?: string } };
    if (payload?.error?.code) code = payload.error.code;
    if (payload?.error?.message) message = payload.error.message;
  } catch {
    // A non-JSON body (proxy, HTML page) keeps the generic message.
  }
  return new ApiError(response.status, code, message, requestId);
}

/** Reads the duplicate/created JSON body that a `200` carries instead of a stream. */
async function outcomeFromJson(response: Response): Promise<UploadOutcome> {
  const payload = (await response.json().catch(() => null)) as {
    document?: Document;
    duplicate?: boolean;
    created?: boolean;
  } | null;

  if (!payload?.document) {
    throw new ApiError(
      response.status,
      'invalid_response',
      'The server sent an unexpected response.',
    );
  }

  const duplicate = payload.duplicate === true || payload.created === false;
  return duplicate
    ? { kind: 'duplicate', document: payload.document }
    : { kind: 'created', document: payload.document };
}

/**
 * Uploads one PDF and reports indexing progress.
 *
 * Resolves with the created (or already-indexed) document. Throws `ApiError`
 * for a rejected file, an over-size body, an `error` frame, or a stream that
 * ends without `done` — the last one means indexing never finished, so it must
 * never be reported as success (§4.3).
 */
export async function uploadDocument(
  asset: UploadAsset,
  handlers: UploadHandlers = {},
): Promise<UploadOutcome> {
  if (isSessionExpired()) {
    notifyUnauthorized();
    throw new ApiError(401, 'token_expired', 'Your session has expired. Please log in again.');
  }

  const token = getAuthToken();

  // Built outside the request's try block on purpose: if the picked file cannot
  // be read, that is not a network failure and must not be reported as one.
  let body: FormData;
  try {
    body = multipartBody(asset);
  } catch {
    throw new ApiError(
      0,
      'file_unreadable',
      'SAGE could not read that file. Please pick it again.',
    );
  }

  let response: Response;
  try {
    response = await fetch(`${getApiBaseUrl()}/api/documents`, {
      method: 'POST',
      headers: {
        Accept: 'text/event-stream',
        // No Content-Type on purpose: the platform sets the multipart boundary.
        ...(token ? { Authorization: `Bearer ${token}` } : {}),
      },
      body,
      signal: handlers.signal,
    });
  } catch (error) {
    if ((error as { name?: string })?.name === 'AbortError') throw error;
    throw new ApiError(0, 'network_error', 'Could not reach SAGE. Check your connection.');
  }

  if (response.status === 401) {
    notifyUnauthorized();
    throw await errorFrom(response);
  }

  const contentType = response.headers.get('content-type') ?? '';

  if (!response.ok) throw await errorFrom(response);

  // A duplicate (or a raced insert) answers with a body, not a stream.
  if (!contentType.includes('text/event-stream')) return outcomeFromJson(response);

  return readStream(response, handlers);
}

/** Consumes the indexing stream. `done` is the only success. */
async function readStream(response: Response, handlers: UploadHandlers): Promise<UploadOutcome> {
  // A holder rather than two `let`s: the frames are applied inside a closure, and
  // TypeScript cannot see through that when narrowing, so it would decide the
  // variables are still `null` at the end of the loop.
  const result: { settled: UploadOutcome | null; error: ApiError | null } = {
    settled: null,
    error: null,
  };

  const handleFrame = (frame: UploadFrame) => {
    if ('progress' in frame) {
      handlers.onProgress?.(frame.progress);
      return;
    }
    if ('done' in frame) {
      const { document, created } = frame.done;
      result.settled = created ? { kind: 'created', document } : { kind: 'duplicate', document };
      return;
    }
    if ('error' in frame) {
      result.error = new ApiError(
        frame.error.status ?? 400,
        frame.error.code || 'invalid_request',
        frame.error.message || 'SAGE could not index that PDF.',
      );
    }
  };

  const reader = response.body?.getReader();

  if (!reader) {
    // Fallback: buffer the whole response, then parse it.
    const text = await response.text();
    const { frames, rest } = splitFrames(text);
    for (const frame of frames) {
      const parsed = parseUploadFrame(frame);
      if (parsed) handleFrame(parsed);
    }
    const tail = parseUploadFrame(rest);
    if (tail) handleFrame(tail);
  } else {
    const decoder = new TextDecoder();
    let buffer = '';

    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value) continue;
      const combined = buffer + decoder.decode(value, { stream: true });
      const split = splitFrames(combined);
      buffer = split.rest;
      for (const frame of split.frames) {
        const parsed = parseUploadFrame(frame);
        if (parsed) handleFrame(parsed);
      }
    }

    const tail = parseUploadFrame(buffer);
    if (tail) handleFrame(tail);
  }

  if (result.error) throw result.error;
  if (!result.settled) {
    // No `done` and no `error`: indexing did not finish. A phantom success here
    // would leave the user believing a file is searchable when it is not.
    throw new ApiError(
      0,
      'upload_incomplete',
      'SAGE could not finish indexing that PDF. Please try again.',
    );
  }

  return result.settled;
}
